export function valueText(value: any, lang: Language): string {
  if (value === null || value === undefined || value === "")
    return lang === "zh" ? "待核对" : "To be confirmed";
  if (typeof value === "boolean")
    return lang === "zh" ? (value ? "是" : "否") : value ? "Yes" : "No";
  if (typeof value === "string" && lang === "zh") return states[value] || value;
  return String(value);
}
